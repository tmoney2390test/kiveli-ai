import type { ImageSource } from 'expo-image';
import manifest from './catalog-artwork.runtime.json';
import { KIVELLI_IMAGE_PLACEHOLDER } from './lib/imageWarmup';

// Public, built-in presentation artwork only. Never put uploads, generated
// media, private references or signed URLs in this immutable catalog.
export const CATALOG_ARTWORK_BASE = 'https://mfysnlghlhxxcwnwpxog.supabase.co/storage/v1/object/public/kivelli-catalog/';
export type CatalogArtworkPath = keyof typeof manifest;

const alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const hex=Array.from({length:256},(_,n)=>n.toString(16).padStart(2,'0'));
function unpack(row:string) {
  const [encoded,dimensions]=row.split('.') as [string,string]; // Generated by scripts/catalog-artwork.mjs.
  let bits=0,value=0,hashes='';
  // Works on Hermes as well as browsers, without Buffer or an atob polyfill.
  for(const c of encoded){value=(value<<6)|alphabet.indexOf(c);bits+=6;if(bits>=8){bits-=8;hashes+=hex[(value>>>bits)&255];}}
  const [w,h,tw,th]=dimensions.split(',').map(Number) as [number,number,number,number];
  const source=(hash:string,width:number,height:number):ImageSource=>{
    const file='v1/'+hash+'.webp';return {uri:CATALOG_ARTWORK_BASE+file,width,height,cacheKey:'kivelli-catalog:'+file};
  };
  return {display:source(hashes.slice(0,64),w,h),thumbnail:source(hashes.slice(64),tw,th)};
}
const entries=new Map<CatalogArtworkPath,ReturnType<typeof unpack>>();
const thumbnailByDisplay=new Map<string,ImageSource>();
for(const path of Object.keys(manifest) as CatalogArtworkPath[]){
  const entry=unpack(manifest[path]);entries.set(path,entry);thumbnailByDisplay.set(entry.display.uri!,entry.thumbnail);
}
export function catalogArtwork(path: CatalogArtworkPath, size: 'display' | 'thumbnail' = 'display'): ImageSource {
  return {...entries.get(path)![size]};
}


/** Do not rewrite custom/private images, signed URLs or local fallback assets. */
export function catalogThumbnail(source: ImageSource | number | undefined): ImageSource | number | undefined {
  return source && typeof source === 'object' && source.uri ? thumbnailByDisplay.get(source.uri) ?? source : source;
}

export function catalogImagePresentation<T>(source:T,failedUri?:string) {
  const uri=source && typeof source==='object' && 'uri' in source && typeof source.uri==='string' ? source.uri : undefined;
  const isCatalog=Boolean(uri?.startsWith(CATALOG_ARTWORK_BASE));
  return {uri,isCatalog,source:isCatalog&&uri===failedUri?KIVELLI_IMAGE_PLACEHOLDER:source};
}
