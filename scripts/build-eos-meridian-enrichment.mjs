import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { WORLD_ID, characters, locations, storyArcs, recurringEvents, worldFacts, buildSchedules } from './eos-meridian-content.mjs';
import { chronology, districtLife, relationshipPerspectives, editorialLocationLore } from './eos-meridian-enrichment.mjs';

export const migrationPath='supabase/migrations/20260914224529_eos_meridian_editorial_enrichment.sql';
const json=value=>`$eos_editorial$${JSON.stringify(value)}$eos_editorial$::jsonb`;
export function renderEnrichmentMigration(){
  const payload={characters:characters.map(c=>({templateId:c.templateId,versionId:c.versionId,slug:c.slug,firstMeeting:c.firstMeeting,life:c.characterBible.editorialLife})),
    locations:locations.filter(p=>p.editorialLife||p.supportingResidents).map(p=>({slug:p.slug,backstory:p.backstory,socialTexture:p.socialTexture,lore:editorialLocationLore(p)})),
    arcs:storyArcs.map(arc=>({...arc,chapters:arc.chapters.map((chapter,index)=>({...chapter,id:`chapter-${index+1}`,userVisibility:index?'visible':'contextual',mayTriggerProactiveMessage:false,mayCreateMoment:false,minimumHoursBeforeNext:index?24:12,eligibleCharacterSlugs:arc.leadSlugs,eligibleLocationSlugs:arc.locationSlugs}))})),
    events:recurringEvents.map((event,index)=>({...event,id:`3b000000-0000-4000-8012-${String(index+1).padStart(12,'0')}`})),
    facts:worldFacts.slice(30),schedules:buildSchedules(),perspectives:relationshipPerspectives,chronology,districtLife};
  return `-- Generated by scripts/build-eos-meridian-enrichment.mjs. Additive Eos editorial pass.
-- No media, intimate/sexual fields, romance settings, boundaries, player memories or choices are overwritten.
begin;
create temporary table eos_editorial_payload(data jsonb) on commit drop;
insert into eos_editorial_payload values (${json(payload)});

-- Append retrieval details without replacing any existing lore, including mature venue material.
create or replace function pg_temp.eos_append_lore(existing jsonb, additions jsonb) returns jsonb language plpgsql as $$
declare result jsonb:=coalesce(existing,'{}'::jsonb); k text; values_to_add jsonb; value_to_add jsonb; current_values jsonb;
begin
 for k,values_to_add in select key,value from jsonb_each(additions) loop
  current_values:=coalesce(result->k,'[]'::jsonb);
  for value_to_add in select value from jsonb_array_elements(values_to_add) loop
   if not current_values @> jsonb_build_array(value_to_add) then current_values:=current_values||jsonb_build_array(value_to_add); end if;
  end loop;
  result:=jsonb_set(result,array[k],current_values);
 end loop;
 return result;
end $$;

-- Snapshot every column outside the deliberately changed narrative keys for an in-transaction guard.
create temporary table eos_editorial_protected on commit drop as
select v.id, to_jsonb(v)-'character_bible'-'updated_at' as protected_columns,
  coalesce(v.character_bible,'{}'::jsonb)-array['editorialLife','currentGoals','ambitions','concerns'] as protected_bible
from public.together_character_versions v
where v.character_template_id in (select (c->>'templateId')::uuid from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'characters') c);

do $$ begin
  if (select count(*) from public.together_character_templates t where t.id in
    (select (c->>'templateId')::uuid from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'characters') c)) <> 47
  then raise exception 'Eos enrichment requires the complete existing 47-character roster'; end if;
end $$;

update public.together_character_versions v
set character_bible=coalesce(v.character_bible,'{}'::jsonb)||jsonb_build_object(
  'editorialLife',c->'life',
  'currentGoals',case when coalesce(v.character_bible->'currentGoals','[]'::jsonb) @> jsonb_build_array(c->'life'->>'weeklyGoal') then v.character_bible->'currentGoals' else coalesce(v.character_bible->'currentGoals','[]'::jsonb)||jsonb_build_array(c->'life'->>'weeklyGoal') end,
  'ambitions',case when coalesce(v.character_bible->'ambitions','[]'::jsonb) @> jsonb_build_array(c->'life'->>'ambition') then v.character_bible->'ambitions' else coalesce(v.character_bible->'ambitions','[]'::jsonb)||jsonb_build_array(c->'life'->>'ambition') end,
  'concerns',case when coalesce(v.character_bible->'concerns','[]'::jsonb) @> jsonb_build_array(c->'life'->>'relationshipTension') then v.character_bible->'concerns' else coalesce(v.character_bible->'concerns','[]'::jsonb)||jsonb_build_array(c->'life'->>'relationshipTension') end),updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'characters') c
where v.character_template_id=(c->>'templateId')::uuid;

-- Replace only the known generated introduction; preserve any independently authored live opener.
update public.together_character_templates t
set first_meeting=coalesce(t.first_meeting,'{}'::jsonb)||jsonb_build_object('opener',c->'firstMeeting'->>'opener'),updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'characters') c
where t.id=(c->>'templateId')::uuid and
  (t.first_meeting->>'opener' like '%has a reason to speak with you that comes from the immediate setting rather than instant attraction.%'
    or t.first_meeting->>'opener'=c->'firstMeeting'->>'opener');

update public.together_locations l
set canonical_lore=pg_temp.eos_append_lore(l.canonical_lore,item->'lore'),
 metadata=coalesce(l.metadata,'{}'::jsonb)||jsonb_build_object('backstory',item->>'backstory','socialTexture',item->>'socialTexture','editorialVersion',3),updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'locations') item
where l.world_id='${WORLD_ID}'::uuid and l.slug=item->>'slug';

update public.together_worlds w set metadata=coalesce(w.metadata,'{}'::jsonb)||jsonb_build_object('editorialVersion',3,'residentScheduleStatus','authored_weekly_v3','worldFactCount',37,'recurringEventCount',9,
 'canonicalLore',coalesce(w.metadata->'canonicalLore','{}'::jsonb)||jsonb_build_object('editorialChronology',p.data->'chronology','districtLife',p.data->'districtLife')),updated_at=now()
from eos_editorial_payload p where w.id='${WORLD_ID}'::uuid;

update public.together_story_arc_templates a set chapters=item->'chapters',min_relationship_stage=item->>'minStage',
 prerequisites=coalesce(a.prerequisites,'{}'::jsonb)||jsonb_build_object('editorialVersion',3,'resolutionScope','player_session','requiresPlayedChoice',true),updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'arcs') item
where a.slug=item->>'slug' and a.specific_world_id='${WORLD_ID}'::uuid;

update public.together_character_relationship_edges e set trust=(item->>'trust')::int,
 metadata=coalesce(e.metadata,'{}'::jsonb)||jsonb_build_object('editorialPerspective',item->>'view','memorySharing','event_only'),
 history=case when position(item->>'view' in coalesce(e.history,''))>0 then e.history else coalesce(e.history,'')||' '||(item->>'view') end,updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'perspectives') item
join public.together_character_templates s on s.slug=item->>'source'
join public.together_character_templates t on t.slug=item->>'target'
where e.world_id='${WORLD_ID}'::uuid and e.source_template_id=s.id and e.target_template_id=t.id;

-- Existing standard events retain all delivery/economic/eligibility settings.
update public.together_event_templates e set narrative_summary=item->>'summary',metadata=coalesce(e.metadata,'{}'::jsonb)||jsonb_build_object('editorialVersion',3),updated_at=now()
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'events') item
where e.id=(item->>'id')::uuid and e.world_id='${WORLD_ID}'::uuid and e.content_level='standard';

insert into public.together_event_templates(id,name,event_type,world_id,default_location_id,participant_template_ids,significance,probability,duration_minutes,narrative_summary,state_effects,user_visibility,proactive_eligible,metadata,active,category,tone,scale,content_level,conditions,followups)
select (item->>'id')::uuid,item->>'name',item->>'eventType','${WORLD_ID}'::uuid,l.id,
 array(select t.id from public.together_character_templates t where t.slug in(select jsonb_array_elements_text(item->'participantSlugs'))),
 .58,.08,90,item->>'summary','{}'::jsonb,'contextual',false,jsonb_build_object('worldSlug','eos-meridian','worldEvent',true,'recurrence',item->'recurrence','scheduleAware',true,'userLocalClock',true,'editorialVersion',3,'resolutionScope','player_session'),true,'social','positive','normal','standard',jsonb_build_object('recurrence',item->'recurrence'),'{}'::text[]
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'events') item
join public.together_locations l on l.world_id='${WORLD_ID}'::uuid and l.slug=item->>'locationSlug'
where item->>'name'='The Rain Is Cancelled'
on conflict(id) do update set narrative_summary=excluded.narrative_summary,metadata=excluded.metadata,updated_at=now();

insert into public.together_world_facts(world_id,slug,title,fact_text,category,truth_mode,knowledge_scope,content_level,topic_tags,trigger_terms,weight,cooldown_turns,active,metadata)
select '${WORLD_ID}'::uuid,item->>'slug',item->>'title',item->>'fact','culture','canonical','public','standard',array['culture','eos-meridian'],array(select jsonb_array_elements_text(item->'triggerTerms')),1,24,true,jsonb_build_object('source','eos_editorial_v3','closedWorld',true)
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'facts') item
on conflict(world_id,slug) do update set fact_text=excluded.fact_text,title=excluded.title,metadata=excluded.metadata,updated_at=now();

-- Refresh only seed schedule templates, not user plans, current activities or scenario state.
delete from public.together_schedule_templates s where s.character_version_id in
 (select (c->>'versionId')::uuid from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'characters') c)
 and s.metadata->>'scheduleMode'='authored' and s.metadata->>'worldSlug'='eos-meridian';
insert into public.together_schedule_templates(character_version_id,day_of_week,start_minute,end_minute,location_id,activity,availability,energy_delta,mood_influence,variation_weight,metadata)
select (item->>'characterVersionId')::uuid,(item->>'dayOfWeek')::int,(item->>'startMinute')::int,(item->>'endMinute')::int,l.id,item->>'activity',item->>'availability',(item->>'energyDelta')::int,item->>'moodInfluence',1,item->'metadata'
from eos_editorial_payload p cross join lateral jsonb_array_elements(p.data->'schedules') item
left join public.together_locations l on l.world_id='${WORLD_ID}'::uuid and l.slug=item->>'locationSlug'
on conflict(character_version_id,day_of_week,start_minute,week_index) do nothing;

do $$ begin
 if exists(select 1 from eos_editorial_protected before join public.together_character_versions after on after.id=before.id
   where before.protected_columns is distinct from to_jsonb(after)-'character_bible'-'updated_at'
      or before.protected_bible is distinct from coalesce(after.character_bible,'{}'::jsonb)-array['editorialLife','currentGoals','ambitions','concerns'])
 then raise exception 'Eos editorial migration changed protected character material'; end if;
end $$;
commit;
`;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  await writeFile(migrationPath,renderEnrichmentMigration());
  console.log(`Generated ${migrationPath}`);
}
